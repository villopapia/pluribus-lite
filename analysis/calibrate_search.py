"""D-SRCH-3: calibrate the real-time search's raise sizes to the paper's subgame size.

Supp p. 13: "During real-time search, the number of action sequences (considering only players'
actions, not chance's actions) in the subgame action abstraction is between 100 and 2,000";
pp. 12-13: between one and six raise sizes. The sets are not published.

Method (the analogue of theta against 664,845,654 for the blueprint, docs/fidelity_report.md):
1. Evidence: Pluribus' logged post-flop bets/raises come from real-time search (Supp p. 19), so
   per (street, raise depth) rank the grid sizes (calibrate_sizes.GRID, `bet_frac_pot`
   convention) by how often Pluribus used them (non all-in).
2. Two size configs (subgame.rs `build_with`):
   - root street: per cell (street x heads-up/multiway) and depth 0 or 1 the top-k sizes,
     k = 1..5 (all-in is always added: at most 6 raise sizes); depth >= 2: {1} + all-in (as the
     published turn/river rule for later raises);
   - later streets of the subgame: a fixed policy (`LATER`): all-in only; pot + all-in for the
     first bet; pot + all-in throughout; half-pot/pot + all-in for the first bet; or pot + all-in
     heads-up and all-in only multiway (`pot_bet_hu`, recommended 2026-11-08). A single
     per-street set cannot work: the heads-up river needs ~5 sizes to reach 100 sequences, and
     the same river inside every turn subgame then pushes those far above 2,000 (measured;
     docs/m4_design.md §2.1).
3. Subgame roots: every flop/turn/river start Pluribus searched from in the 10,000 hands
   (subgame_roots.py, 4,041 roots). Size = action sequences of our subgame under the paper's leaf
   rules (engine `subgame_sizes`).
4. For each later-street policy, per cell choose (k0, k1) maximising the share of that cell's
   roots in [100, 2000]; ties go to the median closest (log scale) to sqrt(100 * 2000). Order
   river -> turn -> flop (a subgame contains the later streets), heads-up before multiway.

Usage:  .venv/Scripts/python calibrate_search.py [--later POLICY ...] [--write POLICY]
  --write: save engine/nlhe/configs/search_root.cfg and search_later.cfg for that policy
"""

from __future__ import annotations

import argparse
import math
import subprocess
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

from calibrate_sizes import GRID

LO, HI = 100, 2_000
CENTRE = math.sqrt(LO * HI)
STREETS = ["preflop", "flop", "turn", "river"]
KMAX = 5
HERE = Path(__file__).resolve().parent
ENGINE = HERE.parent / "engine"
HEADER = "# Generated by analysis/calibrate_search.py (D-SRCH-3; method in its docstring)\n"


def ranked_sizes(d: pd.DataFrame) -> dict[tuple[str, int], list[float]]:
    """(street, depth) -> grid sizes ordered by Pluribus' usage (most frequent first)."""
    a = d[d.action.isin(["bet", "raise"]) & ~d.all_in]
    out = {}
    for street in STREETS:
        for depth in (0, 1):
            x = a[(a.street == street) & (a.raises_before == depth)].bet_frac_pot.to_numpy()
            if len(x):
                snapped = GRID[np.abs(GRID[None, :] - x[:, None]).argmin(1)]
                vc = pd.Series(snapped).value_counts()
                # ties broken by size, for reproducibility
                out[(street, depth)] = [float(v) for v, _ in sorted(vc.items(), key=lambda kv: (-kv[1], kv[0]))]
    return out


def _fmt(v: list[float]) -> str:
    return ", ".join(f"{x:g}" for x in sorted(v))


def root_text(ranked: dict, k: dict, name: str = "search_root") -> str:
    """k[(street, 'hu'|'mw', depth)] = number of top sizes (default 1)."""
    lines = [f"name = {name}", "buckets = 169, 500, 500, 500", "allin = true", "limp = all"]
    for street in STREETS:
        for depth in (0, 1):
            sizes = ranked.get((street, depth), [1.0])
            lines.append(f"{street}.{depth} = {_fmt(sizes[: k.get((street, 'hu', depth), 1)])}")
            if street != "preflop":
                lines.append(f"multiway.{street}.{depth} = {_fmt(sizes[: k.get((street, 'mw', depth), 1)])}")
        lines.append(f"{street}.2+ = 1")
    return "\n".join(lines) + "\n"


LATER = {
    # later streets of a subgame (D-SRCH-3 alternatives): (first-bet sizes, raise sizes); all-in always added
    "allin": ([], []),
    "pot_bet": ([1.0], []),
    "pot_all": ([1.0], [1.0]),
    "half_pot_bet": ([0.5, 1.0], []),
    # heads-up nodes: pot + all-in for the first bet; multiway nodes (3+ in the hand): all-in only
    "pot_bet_hu": ([1.0], []),
}
MULTIWAY_ALLIN_ONLY = {"pot_bet_hu"}


def later_text(mode: str, name: str = "search_later") -> str:
    """Later-street sizes for every post-flop street, heads-up and multiway alike."""
    bet, raise_ = LATER[mode]
    lines = [f"name = {name}", f"# later streets: {mode}", "buckets = 169, 500, 500, 500", "allin = true", "limp = all"]
    for street in STREETS[1:]:
        mw_bet, mw_raise = ([], []) if mode in MULTIWAY_ALLIN_ONLY else (bet, raise_)
        lines += [f"{street}.0 = {_fmt(bet)}", f"multiway.{street}.0 = {_fmt(mw_bet)}", f"multiway.{street}.1 = {_fmt(mw_raise)}", f"{street}.1+ = {_fmt(raise_)}"]
    return "\n".join(lines) + "\n"


def measure(root: str, later: str, street: int | None) -> list[tuple[int, int, int]]:
    """(street, players, sequences) per root; sequences = 2**64-1 when over the tool's cap."""
    exe = ENGINE / "target" / "release" / "subgame_sizes"
    with tempfile.TemporaryDirectory() as td:
        pr, pl = Path(td) / "root.cfg", Path(td) / "later.cfg"
        pr.write_text(root, encoding="utf-8")
        pl.write_text(later, encoding="utf-8")
        cmd = [str(exe), "--config", str(pr), "--later", str(pl), "--roots", str(HERE.parent / "data" / "subgame_roots.tsv"), "--per-root"]
        if street is not None:
            cmd += ["--street", str(street)]
        out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    return [tuple(int(x) for x in f) for f in (line.split("\t") for line in out.splitlines()) if len(f) == 3 and all(x.isdigit() for x in f)]


def score(seqs: list[int]) -> tuple[float, float]:
    """(share in range, -|log(median / centre)|): larger is better."""
    s = sorted(seqs)
    share = sum(LO <= x <= HI for x in s) / len(s)
    return share, -abs(math.log(s[len(s) // 2] / CENTRE))


def calibrate(ranked: dict, mode: str, log=print) -> dict:
    """Current-street top-k per (street, heads-up/multiway, depth), with later streets fixed to `mode`."""
    k: dict = {}
    later = later_text(mode)
    for si in (3, 2, 1):
        street = STREETS[si]
        n0 = min(KMAX, len(ranked.get((street, 0), [1])))
        n1 = min(KMAX, len(ranked.get((street, 1), [1])))
        for cls in ("hu", "mw"):
            best = None
            for k0 in range(1, n0 + 1):
                for k1 in range(1, n1 + 1):
                    tk = dict(k)
                    tk[(street, cls, 0)], tk[(street, cls, 1)] = k0, k1
                    rows = measure(root_text(ranked, tk), later, si)
                    seqs = [n for _, p, n in rows if (p == 2) == (cls == "hu")]
                    sc = score(seqs)
                    if best is None or sc > best[0]:
                        best = (sc, k0, k1, sorted(seqs)[len(seqs) // 2])
            sc, k0, k1, med = best
            k[(street, cls, 0)], k[(street, cls, 1)] = k0, k1
            log(f"  {street:5s} {cls}: k0={k0} k1={k1}  in range {sc[0]:.1%}, median {med}")
    return k


def summary(ranked: dict, k: dict, mode: str) -> tuple[float, int, list[tuple[int, int, int]]]:
    rows = measure(root_text(ranked, k), later_text(mode), None)
    post = sorted(n for s, _, n in rows if s > 0)
    return sum(LO <= x <= HI for x in post) / len(post), post[len(post) // 2], rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--later", choices=sorted(LATER), action="append", help="later-street policy (repeatable; default: all)")
    ap.add_argument("--write", choices=sorted(LATER), help="save search_root.cfg / search_later.cfg for this policy")
    args = ap.parse_args()
    ranked = ranked_sizes(pd.read_parquet(HERE.parent / "data" / "pluribus_decisions.parquet"))
    for mode in args.later or list(LATER):
        print(f"later streets = {mode} {LATER[mode]}")
        k = calibrate(ranked, mode)
        share, med, _ = summary(ranked, k, mode)
        print(f"  => post-flop roots in range {share:.1%}, median {med}")
        if args.write == mode:
            (ENGINE / "nlhe" / "configs" / "search_root.cfg").write_text(HEADER + root_text(ranked, k), encoding="utf-8")
            (ENGINE / "nlhe" / "configs" / "search_later.cfg").write_text(HEADER + later_text(mode), encoding="utf-8")
            print("  written: search_root.cfg, search_later.cfg")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
