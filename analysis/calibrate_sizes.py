"""Derive faithful.cfg preflop/flop raise sizes from Pluribus' observed sizes.

The paper chose blueprint sizes "by hand based on what raise sizes earlier versions of
Pluribus decided to use with significant positive probabilities" (supplement p. 12); the
sets are not published. Our reproducible proxy:

1. snap every observed (non all-in) Pluribus bet/raise to the nearest size on GRID
   (pot fractions, `bet_frac_pot` convention);
2. per (street, raise depth), keep grid sizes whose share of that depth's bets is >= theta,
   always keeping the most frequent size; depths with no data use {1.0};
3. turn/river use the paper's published rule ({0.5, 1} then {1}), independent of theta.

The threshold theta is then tuned so the betting tree has about 664,845,654 action
sequences (the paper's count, p. 13); see `docs/fidelity_report.md`.

Usage:  .venv/Scripts/python calibrate_sizes.py --theta 0.10 [--out ../engine/nlhe/configs/x.cfg]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

GRID = np.array([0.25, 0.33, 0.4, 0.5, 0.6, 0.75, 0.88, 1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0])
MAX_DEPTH = {"preflop": 3, "flop": 2}  # depth >= this uses {1.0}


def observed_shares(d: pd.DataFrame) -> dict[tuple[str, int], pd.Series]:
    """(street, depth) -> share of each grid size among Pluribus' non all-in bets/raises."""
    a = d[d.action.isin(["bet", "raise"]) & ~d.all_in]
    out = {}
    for street, maxd in MAX_DEPTH.items():
        for depth in range(maxd):
            x = a[(a.street == street) & (a.raises_before == depth)].bet_frac_pot.to_numpy()
            if len(x) == 0:
                continue
            snapped = GRID[np.abs(GRID[None, :] - x[:, None]).argmin(1)]
            out[(street, depth)] = pd.Series(snapped).value_counts(normalize=True)
    return out


def size_sets(shares: dict[tuple[str, int], pd.Series], theta: float) -> dict[tuple[str, int], list[float]]:
    sets = {}
    for key, s in shares.items():
        keep = sorted(float(v) for v, p in s.items() if p >= theta)
        if not keep:
            keep = [float(s.idxmax())]
        sets[key] = keep
    return sets


def config_text(name: str, sets: dict[tuple[str, int], list[float]], theta: float, buckets: int = 200) -> str:
    fmt = lambda v: ", ".join(f"{x:g}" for x in v)  # noqa: E731
    lines = [
        f"# Generated by analysis/calibrate_sizes.py --theta {theta}",
        "# Structure per the paper (docs/fidelity_spec.md); preflop/flop sizes = observed proxy.",
        f"name = {name}",
        f"buckets = 169, {buckets}, {buckets}, {buckets}",
        "allin = true",
        "limp = all",
        "crowded_players = 0",
        "river_method = on_the_fly",
        "avg_strategy_streets = preflop",
    ]
    for street, maxd in MAX_DEPTH.items():
        for depth in range(maxd):
            if (street, depth) in sets:
                lines.append(f"{street}.{depth} = {fmt(sets[(street, depth)])}")
        lines.append(f"{street}.{maxd}+ = 1")
    lines += ["turn.0 = 0.5, 1", "turn.1+ = 1", "river.0 = 0.5, 1", "river.1+ = 1"]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--theta", type=float, required=True)
    ap.add_argument("--name", default=None)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    here = Path(__file__).resolve().parent
    d = pd.read_parquet(here.parent / "data" / "pluribus_decisions.parquet")
    name = args.name or f"faithful_t{int(round(args.theta * 100)):02d}"
    txt = config_text(name, size_sets(observed_shares(d), args.theta), args.theta)
    if args.out:
        args.out.write_text(txt, encoding="utf-8")
    print(txt, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
